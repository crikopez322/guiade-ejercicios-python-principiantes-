num1 = int(input("ingresa el primer número: "))
num2 = int(input("ingresa el segundo número: "))
operador = input("ingresa el operador (+, -, *, /): ")

if operador == "+":
    print("el resultado es:")
    print(num1 + num2)

if operador == "-":
    print("el resultado es:")
    print(num1 - num2)

if operador == "*":
    print("el resultado es:")
    print(num1 * num2)

if operador == "/":
    print("el resultado es:")
    print(num1 / num2)